/**
 * Builds the landing letters ("SACHIN") as plain geometry data, so the world
 * can swap them in for the original letters without loading a font at runtime.
 * Run: node scripts/landing-letters.mjs
 */
import fs from 'node:fs'
import { TTFLoader } from './TTFLoader.node.js' // three's TTFLoader, with opentype.js from npm instead of a CDN
import { Font } from 'three/addons/loaders/FontLoader.js'
import { TextGeometry } from 'three/addons/geometries/TextGeometry.js'

const TEXT = 'SACHIN'
const HEIGHT = 1.45 // same letter height as the originals
const DEPTH = 0.44

const file = fs.readFileSync(new URL('../static/fonts/Pally-Bold.ttf', import.meta.url))
const font = new Font(new TTFLoader().parse(file.buffer.slice(file.byteOffset, file.byteOffset + file.byteLength)))

const round = (a) => Array.from(a, (v) => Math.round(v * 500) / 500)
const letters = []
for(const char of TEXT)
{
    let geometry = new TextGeometry(char, { font, size: 1, depth: DEPTH, curveSegments: 4, bevelEnabled: false })
    geometry.computeBoundingBox()
    const box = geometry.boundingBox
    const scale = HEIGHT / (box.max.y - box.min.y)
    geometry.scale(scale, scale, 1)
    geometry.computeBoundingBox()
    const b = geometry.boundingBox
    geometry.translate(-(b.min.x + b.max.x) / 2, -(b.min.y + b.max.y) / 2, -(b.min.z + b.max.z) / 2)
    geometry.computeBoundingBox()
    const s = geometry.boundingBox.max.clone().sub(geometry.boundingBox.min)
    letters.push({
        char,
        size: round([ s.x, s.y, s.z ]),
        position: round(geometry.attributes.position.array),
    })
}

fs.writeFileSync(
    new URL('../sources/data/landingLetters.js', import.meta.url),
    `// Generated by scripts/landing-letters.mjs from Pally Bold. Do not edit by hand.\nexport default ${JSON.stringify(letters)}\n`
)
console.log(letters.map((l) => `${l.char} ${l.size.join('x')} ${l.position.length / 3} verts`).join('\n'))
